// Content register: one row per catalogue topic with its page and verification status.
// Reads data/curriculum.json, content/topics/*.md front matter, research/verification/*.json and
// research/iyf-materials/manifest.json. Writes research/content-register.md.
//
// Usage: node tools/register.mjs

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const cur = JSON.parse(readFileSync(join(ROOT, 'data/curriculum.json'), 'utf8'));
const manPath = join(ROOT, 'research/iyf-materials/manifest.json');
const man = existsSync(manPath) ? JSON.parse(readFileSync(manPath, 'utf8')) : { rows: {}, items: {} };

// Format check (no model needed): every section A–Q and S1–S8, a references list, quiz answers.
function lint(src) {
  const missing = [];
  for (const l of 'ABCDEFGHIJKLMNOPQR') if (!new RegExp(`^## ${l}\\. `, 'm').test(src)) missing.push(l);
  if (!/^# Part 2: For students\s*$/m.test(src)) missing.push('Part 2');
  else for (let i = 1; i <= 8; i++) if (!new RegExp(`^## S${i}\\. `, 'm').test(src)) missing.push(`S${i}`);
  if (/^# Part 2/m.test(src) && !/\*\*Answers:\*\*/.test(src)) missing.push('quiz answers');
  if (!/^references:\n\s+- /m.test(src)) missing.push('references');
  return missing;
}

function front(id) {
  const p = join(ROOT, `content/topics/${id}.md`);
  if (!existsSync(p)) return null;
  const src = readFileSync(p, 'utf8');
  const fm = src.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? '';
  const get = k => fm.match(new RegExp(`^${k}:\\s*(.+)$`, 'm'))?.[1]?.replace(/\s+#.*$/, '').trim();
  return { review: get('review') ?? 'drafted', sensitive: get('sensitive') === 'true', missing: lint(src) };
}

function verification(id) {
  const p = join(ROOT, `research/verification/${id}.json`);
  if (!existsSync(p)) return '';
  const r = JSON.parse(readFileSync(p, 'utf8')).results;
  const ok = r.filter(x => x.status.startsWith('exists')).length;
  return `${ok}/${r.length}` + (ok < r.length ? ' ⚠' : '');
}

const iyfText = t => t.siteRows.some(r => (man.rows[r] ?? []).some(k => man.items[k]?.status === 'text'));

const rows = [];
const totals = { topics: 0, pages: 0, checked: 0, approved: 0 };
for (const b of cur.batches) {
  const topics = cur.topics.filter(t => t.batch === b.code && t.kind === 'topic');
  rows.push('', `## ${b.short} (${topics.length})`, '', '| ID | Title | IYF notes | Page | Review | Refs found | Sensitive | Format |', '|---|---|---|---|---|---|---|---|');
  for (const t of topics) {
    const f = front(t.id);
    totals.topics++;
    if (f) totals.pages++;
    if (f && f.review !== 'drafted') totals.checked++;
    if (f?.review === 'approved') totals.approved++;
    rows.push(`| ${t.id} | ${t.title.slice(0, 70).replace(/\|/g, '/')} | ${iyfText(t) ? 'yes' : ''} | ${f ? 'yes' : '—'} | ` +
      `${f?.review ?? ''} | ${verification(t.id)} | ${f?.sensitive ? 'yes' : ''} | ` +
      `${!f ? '' : f.missing.length ? 'missing ' + f.missing.join(' ') : 'ok'} |`);
    if (f?.missing.length) console.log(`${t.id}: missing ${f.missing.join(', ')}`);
  }
}

const head = [
  '# Content register', '',
  `Generated by \`node tools/register.mjs\` on ${new Date().toISOString().slice(0, 10)}. A page counts as done only when its`,
  'review status is `approved`; "Refs found" is the automatic check only.', '',
  `**${totals.pages} of ${totals.topics} topics have a page** · ${totals.checked} past drafted · ${totals.approved} approved.`,
];
writeFileSync(join(ROOT, 'research/content-register.md'), head.concat(rows).join('\n') + '\n');
console.log(`${totals.pages}/${totals.topics} pages, ${totals.checked} checked, ${totals.approved} approved`);
